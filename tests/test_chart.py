"""Tests for chart loading.

Both the chart that ships with the game and a set of broken files are checked:
a chart that parses but puts a note in lane 7 has to be rejected rather than
crash the game three seconds into a run.
"""

from __future__ import annotations  # modern hint syntax

import json  # to write the broken files
import sys  # to reach the repo root
import tempfile  # for the temp dirs
import unittest  # the runner
from pathlib import Path  # for the temp paths

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # the same line in every test file, tests run from any folder

from beatlanes import config  # noqa: E402  # lane count and the shipped chart path
from beatlanes.chart import Chart, ChartError, ChartNote, load_chart  # noqa: E402  # everything under test


def write_chart(directory: Path, payload) -> Path:  # helper: dump a payload and hand back the path
    path = directory / "chart.json"  # always the same name
    path.write_text(json.dumps(payload), encoding="utf-8")  # json on disk
    return path  # caller loads it


class ShippedChartTests(unittest.TestCase):  # the real chart the game ships
    """The chart generated by tools/make_chart.py has to be playable."""

    def setUp(self):  # skip if the chart was never generated
        if not config.CHART_PATH.exists():  # does the file exist
            self.skipTest(f"{config.CHART_PATH.name} not generated yet - run tools/make_chart.py")  # say how to make it
        self.chart = load_chart(config.CHART_PATH)  # load the real one

    def test_notes_are_in_play_order(self):  # the play order rule
        times = [note.time_ms for note in self.chart.notes]  # collect the times
        self.assertEqual(times, sorted(times))  # they must already be sorted

    def test_indices_match_position(self):  # index follows position
        for position, note in enumerate(self.chart.notes):  # walk with position
            self.assertEqual(note.index, position)  # index equals position

    def test_every_lane_is_used(self):  # no dead lanes
        self.assertEqual(sum(self.chart.lane_counts), self.chart.note_count)  # counts add up to the total
        self.assertTrue(all(count > 0 for count in self.chart.lane_counts), self.chart.lane_counts)  # and every lane has at least one

    def test_all_lanes_are_inside_the_window(self):  # lanes stay in range
        for note in self.chart.notes:  # every note
            self.assertGreaterEqual(note.lane, 0)  # not below zero
            self.assertLess(note.lane, config.LANE_COUNT)  # not past lane 3

    def test_notes_start_after_the_intro(self):  # the intro belongs to the countdown
        self.assertGreater(self.chart.notes[0].time_ms, 0)  # first note is not at zero

    def test_tempo_is_recorded(self):  # bpm recorded for the grid
        self.assertAlmostEqual(self.chart.bpm, 120.0)  # the shipped tempo


class BrokenChartTests(unittest.TestCase):  # bad input has to be rejected, not crash later
    def setUp(self):  # fresh temp dir per test
        self._tmp = tempfile.TemporaryDirectory()  # a throwaway folder
        self.directory = Path(self._tmp.name)  # the folder for the bad files

    def tearDown(self):  # clean up
        self._tmp.cleanup()  # gone

    def test_missing_file(self):  # no file at all
        with self.assertRaises(ChartError):  # must raise
            load_chart(self.directory / "nope.json")  # nothing there

    def test_not_json(self):  # rubbish text
        path = self.directory / "bad.json"  # the bad file
        path.write_text("{ this is not json", encoding="utf-8")  # not json
        with self.assertRaises(ChartError):  # must raise
            load_chart(path)  # and it does

    def test_no_notes(self):  # an empty note list
        with self.assertRaises(ChartError):  # must raise
            load_chart(write_chart(self.directory, {"title": "empty", "notes": []}))  # nothing to play

    def test_lane_out_of_range(self):  # lane past the end
        payload = {"notes": [{"time": 100, "lane": config.LANE_COUNT}]}  # lane 4 in a 4 lane game
        with self.assertRaises(ChartError):  # must raise
            load_chart(write_chart(self.directory, payload))  # and it does

    def test_negative_time(self):  # time going backwards
        payload = {"notes": [{"time": -1, "lane": 0}]}  # minus one ms
        with self.assertRaises(ChartError):  # must raise
            load_chart(write_chart(self.directory, payload))  # and it does

    def test_missing_fields(self):  # a note without a time
        payload = {"notes": [{"lane": 0}]}  # lane only
        with self.assertRaises(ChartError):  # must raise
            load_chart(write_chart(self.directory, payload))  # and it does

    def test_note_that_is_not_an_object(self):  # a bare number is not a note
        payload = {"notes": [1000]}  # just an int
        with self.assertRaises(ChartError):  # must raise
            load_chart(write_chart(self.directory, payload))  # and it does


class OrderingTests(unittest.TestCase):  # loading fixes the order
    def setUp(self):  # fresh temp dir per test
        self._tmp = tempfile.TemporaryDirectory()  # a throwaway folder
        self.directory = Path(self._tmp.name)  # the folder

    def tearDown(self):  # clean up
        self._tmp.cleanup()  # gone

    def test_notes_are_sorted_and_reindexed(self):  # sort and reindex in one pass
        payload = {  # deliberately shuffled
            "title": "out of order",  # the title
            "bpm": 90,  # a slower bpm, just because
            "notes": [  # the shuffled notes
                {"time": 3000, "lane": 1},  # third in the file
                {"time": 1000, "lane": 3},  # first by time
                {"time": 2000, "lane": 0},  # second by time
            ],  # third in the file
        }  # payload done
        chart = load_chart(write_chart(self.directory, payload))  # load it
        self.assertEqual([note.time_ms for note in chart.notes], [1000, 2000, 3000])  # times now in order
        self.assertEqual([note.index for note in chart.notes], [0, 1, 2])  # indexes follow the new order
        self.assertEqual([note.lane for note in chart.notes], [3, 0, 1])  # lanes travel with their notes

    def test_same_moment_is_ordered_by_lane(self):  # ties break by lane
        payload = {  # all at the same ms
            "notes": [  # same time
                {"time": 500, "lane": 3},  # lane 3
                {"time": 500, "lane": 0},  # lane 0
                {"time": 500, "lane": 2},  # lane 2
            ]  # lane 2
        }  # payload done
        chart = load_chart(write_chart(self.directory, payload))  # load it
        self.assertEqual([note.lane for note in chart.notes], [0, 2, 3])  # lanes sorted within the moment

    def test_chart_length_is_the_last_note(self):  # length is the last note
        payload = {"notes": [{"time": 100, "lane": 0}, {"time": 9000, "lane": 1}]}  # one early, one late
        chart = load_chart(write_chart(self.directory, payload))  # load it
        self.assertEqual(chart.length_ms, 9000)  # the late one wins

    def test_missing_title_falls_back_to_the_filename(self):  # no title, use the file name
        payload = {"notes": [{"time": 100, "lane": 0}]}  # no title key
        chart = load_chart(write_chart(self.directory, payload))  # load it
        self.assertEqual(chart.title, "chart")  # falls back to chart.json's stem

    def test_chart_is_a_value(self):  # the frozen value check
        chart = Chart(title="t", bpm=120.0, notes=(ChartNote(0, 0, 100),))  # a tiny hand-made chart
        self.assertEqual(chart.note_count, 1)  # one note
        self.assertEqual(chart.length_ms, 100)  # length from that note



class EveryShippedChartTests(unittest.TestCase):  # week 12: all three charts on the title screen
    """Every chart the title screen offers has to load, and has to fit inside
    the song. The hand chart did not: its last six notes came after the music
    had stopped, and nothing checked, because the old tests only looked at the
    generated chart."""

    def test_every_chart_loads(self):  # nothing on the picker can crash a run
        for path in config.CHARTS:  # all of them
            with self.subTest(chart=path.name):  # say which one failed
                self.assertGreater(load_chart(path).note_count, 0)  # loads, and has notes

    def test_every_note_ends_inside_the_song(self):  # the week 12 hand chart bug
        from tools import beatplan  # the song length lives with the beat plan

        for path in config.CHARTS:  # all of them
            with self.subTest(chart=path.name):  # say which one failed
                self.assertLessEqual(load_chart(path).length_ms, beatplan.SONG_MS)  # the last note or tail lands before the music stops

    def test_the_note_count_field_matches_the_notes(self):  # the hand chart said 64 for 60 notes
        for path in config.CHARTS:  # all of them
            raw = json.loads(path.read_text(encoding="utf-8"))  # the file as written
            if "note_count" not in raw:  # the field is optional
                continue  # nothing to compare
            with self.subTest(chart=path.name):  # say which one failed
                self.assertEqual(raw["note_count"], len(raw["notes"]))  # the field tells the truth

    def test_the_holds_chart_has_holds_and_taps(self):  # the point of the third chart
        chart = load_chart(config.CHART_3_PATH)  # the week 12 chart
        self.assertGreater(chart.hold_count, 0)  # some holds
        self.assertLess(chart.hold_count, chart.note_count)  # and some taps too


class HoldChartTests(unittest.TestCase):  # week 12: the optional "hold" field
    def setUp(self):  # fresh temp dir per test
        self._tmp = tempfile.TemporaryDirectory()  # a throwaway folder
        self.directory = Path(self._tmp.name)  # the folder

    def tearDown(self):  # clean up
        self._tmp.cleanup()  # gone

    def load(self, *notes) -> Chart:  # helper: a chart from note dicts
        return load_chart(write_chart(self.directory, {"notes": list(notes)}))  # write and load

    def test_no_hold_field_means_a_tap(self):  # the old charts keep working
        note = self.load({"time": 1000, "lane": 0}).notes[0]  # a plain note
        self.assertEqual(note.hold_ms, 0)  # no tail
        self.assertFalse(note.is_hold)  # so a tap
        self.assertEqual(note.end_ms, 1000)  # over at its own time

    def test_a_hold_keeps_its_tail(self):  # the new field is read
        note = self.load({"time": 1000, "lane": 2, "hold": 1500}).notes[0]  # a hold
        self.assertTrue(note.is_hold)  # recognised
        self.assertEqual(note.end_ms, 2500)  # head plus tail

    def test_chart_length_includes_the_last_tail(self):  # the run must not stop mid-hold
        chart = self.load({"time": 1000, "lane": 0, "hold": 3000}, {"time": 2000, "lane": 1})  # the hold ends last
        self.assertEqual(chart.length_ms, 4000)  # the tail, not the later head
        self.assertEqual(chart.hold_count, 1)  # one of the two is a hold

    def test_a_negative_hold_is_rejected(self):  # tails cant point backwards
        with self.assertRaises(ChartError):  # must raise
            self.load({"time": 1000, "lane": 0, "hold": -10})  # minus ten ms

    def test_a_hold_that_is_not_a_number_is_rejected(self):  # rubbish in the field
        with self.assertRaises(ChartError):  # must raise
            self.load({"time": 1000, "lane": 0, "hold": "long"})  # a word, not ms

    def test_a_note_inside_a_hold_in_the_same_lane_is_rejected(self):  # the key is already down
        with self.assertRaises(ChartError):  # must raise
            self.load({"time": 1000, "lane": 1, "hold": 1000}, {"time": 1500, "lane": 1})  # starts halfway up the tail

    def test_a_note_in_another_lane_during_a_hold_is_fine(self):  # the other hand is free
        chart = self.load({"time": 1000, "lane": 1, "hold": 1000}, {"time": 1500, "lane": 3})  # same moment, other lane
        self.assertEqual(chart.note_count, 2)  # both loaded

    def test_the_same_lane_is_free_again_after_the_tail(self):  # one beat later is fine
        chart = self.load({"time": 1000, "lane": 1, "hold": 1000}, {"time": 2500, "lane": 1})  # after the tail
        self.assertEqual(chart.note_count, 2)  # both loaded


if __name__ == "__main__":  # run directly
    unittest.main()  # run the tests
